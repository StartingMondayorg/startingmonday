#!/usr/bin/env node

import fs from 'node:fs'
import path from 'node:path'

const ROOT = process.cwd()
const DOCS_DIR = path.join(ROOT, 'docs')
const OUTPUT = path.join(DOCS_DIR, 'index.md')
const CHECK_ONLY = process.argv.includes('--check')

const DOCUMENT_EXTENSIONS = new Set([
  '.md', '.mdx', '.txt', '.csv', '.json', '.html', '.htm', '.ics',
  '.doc', '.docx', '.pdf', '.rtf', '.png', '.jpg', '.jpeg', '.zip',
])

const DOMAIN_ORDER = [
  'governance',
  'strategy',
  'product',
  'engineering',
  'evidence',
  'status',
  'operations',
  'content',
  'research',
  'outreach',
  'onboarding',
  'business',
  'archive',
  'inbox',
  'other',
]

const DOMAIN_DESCRIPTIONS = {
  governance: 'Decisions, policies, controls, standards, and document lifecycle rules.',
  strategy: 'Product, market, channel, roadmap, and implementation plans.',
  product: 'Product requirements, personas, features, journeys, and user-facing specifications.',
  engineering: 'Technical plans, migration notes, architecture, and development references.',
  evidence: 'Validation artifacts, readiness records, source-rights evidence, and proof cases.',
  status: 'Generated or dated operational summaries, checkpoints, and phase closeouts.',
  operations: 'Runbooks, monitoring, support, reliability, and recurring operating procedures.',
  content: 'Marketing copy, editorial work, synthetic council reviews, and publishing assets.',
  research: 'Market research, source maps, behavioral research, and analysis.',
  outreach: 'Outreach playbooks, templates, contact exports, and campaign artifacts.',
  onboarding: 'Setup, first-use, user guides, and onboarding flows.',
  business: 'Commercial strategy, sales plans, partner materials, and business assets.',
  archive: 'Historical documents retained for provenance but not active operating guidance.',
  inbox: 'Newly received documents awaiting review or classification.',
  other: 'Documents that do not yet fit a maintained domain.',
}

function walk(dir) {
  const files = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const fullPath = path.join(dir, entry.name)
    if (entry.isDirectory()) files.push(...walk(fullPath))
    else if (DOCUMENT_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) files.push(fullPath)
  }
  return files
}

function domainFor(relativePath) {
  const first = relativePath.split('/')[0]
  return DOMAIN_ORDER.includes(first) ? first : 'other'
}

function displayTitle(relativePath) {
  const fullPath = path.join(ROOT, 'docs', relativePath)
  if (path.extname(relativePath).toLowerCase() === '.md') {
    const firstHeading = fs.readFileSync(fullPath, 'utf8').match(/^#\s+(.+)$/m)?.[1]?.trim()
    if (firstHeading) return firstHeading
  }
  return path.basename(relativePath, path.extname(relativePath)).replace(/[-_]+/g, ' ')
}

function linkFor(relativePath) {
  return `[${relativePath}](${relativePath.split('/').map(encodeURIComponent).join('/')})`
}

function generate() {
  const files = walk(DOCS_DIR)
    .map((filePath) => path.relative(DOCS_DIR, filePath).replace(/\\/g, '/'))
    .filter((relativePath) => relativePath !== 'index.md')
    .sort((a, b) => a.localeCompare(b))

  const grouped = new Map(DOMAIN_ORDER.map((domain) => [domain, []]))
  for (const file of files) grouped.get(domainFor(file)).push(file)

  const lines = [
    '# Starting Monday Documentation Index',
    '',
    '> Generated by `scripts/generate-docs-index.mjs`. Do not edit this file manually.',
    '',
    `Documents indexed: **${files.length}**`,
    '',
    '## Taxonomy',
    '',
    '| Domain | Purpose | Files |',
    '| --- | --- | ---: |',
  ]

  for (const domain of DOMAIN_ORDER) {
    const entries = grouped.get(domain)
    if (!entries.length) continue
    lines.push(`| [${domain}/](${domain}/) | ${DOMAIN_DESCRIPTIONS[domain]} | ${entries.length} |`)
  }

  lines.push('', '## Documents', '')
  for (const domain of DOMAIN_ORDER) {
    const entries = grouped.get(domain)
    if (!entries.length) continue
    lines.push(`### ${domain}`, '')
    for (const file of entries) lines.push(`- ${linkFor(file)} — ${displayTitle(file)}`)
    lines.push('')
  }

  return `${lines.join('\n')}\n`
}

const output = generate()
if (CHECK_ONLY) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : ''
  if (current !== output) {
    console.error('docs:index is stale; run npm run docs:index')
    process.exit(1)
  }
  console.log('docs:index is current')
} else {
  fs.writeFileSync(OUTPUT, output, 'utf8')
  console.log(`docs:index generated: ${OUTPUT}`)
}
